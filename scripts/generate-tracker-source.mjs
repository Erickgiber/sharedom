/**
 * Bundles the standalone tracker into a single IIFE and embeds it as a string module, so that
 * `sharedom/testing` can inject it with page.addInitScript() / page.evaluateOnNewDocument()
 * without reading files at runtime (works the same in ESM, CJS and bundled test runners).
 */
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(rootDir, 'src/tracker-standalone.ts');
const outFile = path.join(rootDir, 'src/tracker-source.generated.ts');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  target: 'es2022',
  minify: true,
  write: false,
  legalComments: 'none',
});

const code = result.outputFiles[0].text;
const banner = `// Generated by scripts/generate-tracker-source.mjs — do not edit by hand.\n`;
fs.writeFileSync(outFile, `${banner}export const TRACKER_SOURCE = ${JSON.stringify(code)};\n`, 'utf8');

console.log(
  `✅ tracker source embedded (${(code.length / 1024).toFixed(1)} KB) → ${path.relative(rootDir, outFile)}`
);
